const enAll = { ...en, ...CODE_EN };
const esAll: typeof enAll = { ...es, ...CODE_ES };

export const STRINGS: Record<UiLang, typeof enAll> = { en: enAll, es: esAll };
export type StudioStrings = typeof enAll;

export function resolveUiLang(pref: 'auto' | UiLang | undefined): UiLang {
  if (pref === 'es' || pref === 'en') return pref;
  if (typeof navigator !== 'undefined' && /^es\b/i.test(navigator.language || '')) return 'es';
  return 'en';
}
