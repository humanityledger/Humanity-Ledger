#!/usr/bin/env node
/**
 * scripts/aztec/pin-artifacts.mjs — pins the aztec-nr contract artifacts the product uses.
 *
 * Value on Aztec moves only through aztec-nr contracts (Path A: notes, network nullifiers,
 * private functions, proofs made on the device by the PXE). This writes the SHA-256 of every
 * committed artifact in contracts/aztec/<crate>/target/*.json to lib/aztec/artifact-pins.ts, which
 * GET /api/security/integrity publishes. test/unit/aztec/artifact-pins.test.ts fails when an
 * artifact changes without its pin.
 *
 *   node scripts/aztec/pin-artifacts.mjs           # rewrite the pins
 *   node scripts/aztec/pin-artifacts.mjs --check   # exit 1 if a pin is stale or missing
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = 'contracts/aztec';
const OUT = 'lib/aztec/artifact-pins.ts';

export function currentPins() {
  const pins = [];
  for (const crate of readdirSync(ROOT).sort()) {
    const dir = join(ROOT, crate, 'target');
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).sort()) {
      if (!f.endsWith('.json')) continue;
      const path = `${dir}/${f}`;
      const json = JSON.parse(readFileSync(path, 'utf8'));
      pins.push({
        contract: json.name ?? f.replace(/\.json$/, '').split('-').pop(),
        crate,
        artifact: path,
        sha256: createHash('sha256').update(readFileSync(path)).digest('hex'),
        noirVersion: typeof json.noir_version === 'string' ? json.noir_version.split('+')[0] : undefined,
      });
    }
  }
  return pins;
}

function render(pins) {
  const rows = pins
    .map(
      (p) =>
        `  {\n    contract: ${JSON.stringify(p.contract)},\n    crate: ${JSON.stringify(p.crate)},\n    artifact: ${JSON.stringify(p.artifact)},\n    sha256: ${JSON.stringify(p.sha256)},\n` +
        (p.noirVersion ? `    noirVersion: ${JSON.stringify(p.noirVersion)},\n` : '') +
        `  },`,
    )
    .join('\n');
  return `/**
 * lib/aztec/artifact-pins.ts — generated by scripts/aztec/pin-artifacts.mjs. Do not edit by hand.
 *
 * SHA-256 of each committed aztec-nr artifact (contracts/aztec/<crate>/target). These are the
 * contracts the product deploys or calls; where each one runs is recorded in deployments/*.json.
 * Regenerate after \`aztec compile\`: node scripts/aztec/pin-artifacts.mjs
 */
export interface ArtifactPin {
  contract: string;
  crate: string;
  artifact: string;
  sha256: string;
  noirVersion?: string;
}

export const AZTEC_ARTIFACT_PINS: readonly ArtifactPin[] = Object.freeze([
${rows}
]);
`;
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/'));
if (isMain || process.argv[1]?.endsWith('pin-artifacts.mjs')) {
  const next = render(currentPins());
  if (process.argv.includes('--check')) {
    const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (now !== next) {
      console.error(`${OUT} is stale: run node scripts/aztec/pin-artifacts.mjs`);
      process.exit(1);
    }
    console.log(`ok  ${OUT} matches ${currentPins().length} artifacts`);
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT}`);
  }
}
