import { vi } from 'vitest';
import fc from 'fast-check';

/**
 * Parser for special protocol messages:
 *   __ZK_PAYMENT_V1__{"amount": "10", "txHash": "0x..."}__
 *   __ZK_INVOICE_V1__{"reference": "REF-123"}__
 */
export interface ZkSpecialMessage {
  type: string;
  payload: Record<string, unknown>;
}

export function parseSpecialMessage(content: string): ZkSpecialMessage | null {
  if (typeof content !== 'string') return null;
  // Guard against memory bomb / excessive length
  if (content.length > 100_000) return null;

  const match = content.match(/^__ZK_([A-Z0-9_]+)__(\{.*\})__$/);
  if (!match) return null;

  try {
    const type = match[1];
    const parsed = JSON.parse(match[2]);
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
      return null;
    }
    return { type, payload: parsed };
  } catch {
    return null;
  }
}

describe('J-014: Fuzzing Special Message Parsers with fast-check', () => {
  it('safely handles 10,000 arbitrary strings without throwing or crashing', () => {
    fc.assert(
      fc.property(fc.fullUnicodeString(), (str) => {
        // Must never throw an unhandled exception
        const result = parseSpecialMessage(str);
        if (result !== null) {
          expect(typeof result.type).toBe('string');
          expect(typeof result.payload).toBe('object');
        }
      }),
      { numRuns: 10_000 }
    );
  });

  it('correctly parses well-formed special messages generated by property test', () => {
    fc.assert(
      fc.property(
        fc.constantFrom('PAYMENT_V1', 'ESCROW_RELEASE', 'INVOICE_V1', 'STREAM_CREATE'),
        fc.dictionary(fc.string({ minLength: 1, maxLength: 20 }), fc.string({ maxLength: 50 })),
        (type, payload) => {
          const raw = `__ZK_${type}__${JSON.stringify(payload)}__`;
          const parsed = parseSpecialMessage(raw);
          expect(parsed).not.toBeNull();
          expect(parsed?.type).toBe(type);
          expect(parsed?.payload).toEqual(payload);
        }
      ),
      { numRuns: 1_000 }
    );
  });
});
