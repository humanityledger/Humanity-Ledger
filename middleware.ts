export function isPublicPath(pathname: string): boolean {
  if (PUBLIC_PATHS.has(pathname)) return true;
  return PUBLIC_PREFIXES.some(prefix => matchesPrefix(pathname, prefix));
}

/**
 * A prefix ending in "/" covers itself and all its subpaths.
 * Matches must occur at path segment boundaries so that e.g. '/api/settings'
 * does not inadvertently match '/api/settings-export'.
 */
export function matchesPrefix(pathname: string, prefix: string): boolean {
  const normalizedPrefix = prefix.endsWith('/') ? prefix.slice(0, -1) : prefix;
  return pathname === normalizedPrefix || pathname.startsWith(normalizedPrefix + '/');
}

/**
 * checkCsrf — Fails closed on state-changing API mutations (POST, PUT, PATCH, DELETE).
 * Verifies Fetch Metadata (Sec-Fetch-Site) or allowed Origin header.
 */
export function checkCsrf(req: NextRequest): NextResponse | null {
  const method = req.method.toUpperCase();
  if (!['POST', 'PUT', 'PATCH', 'DELETE'].includes(method)) {
    return null;
  }

  const secFetchSite = req.headers.get('sec-fetch-site');
  if (secFetchSite) {
    if (secFetchSite === 'same-origin' || secFetchSite === 'same-site') {
      return null;
    }
    return NextResponse.json(
      { error: 'Forbidden: Cross-site mutation rejected (CSRF protection)' },
      { status: 403 }
    );
  }

  // Fallback when Sec-Fetch-Site is not provided (older browsers, webviews, non-fetch callers)
  const origin = req.headers.get('origin');
  if (origin) {
    const appUrl = process.env.NEXT_PUBLIC_APP_URL;
    const allowed = new Set(['capacitor://localhost', 'ionic://localhost']);
    if (appUrl) {
      try {
        allowed.add(new URL(appUrl).origin);
      } catch {
        allowed.add(appUrl);
      }
    }
    // Local dev origins only outside production: in production any page a
    // visitor runs on their own machine at localhost:3000 would otherwise
    // pass this check with their cookies attached.
    if (process.env.NODE_ENV !== 'production') {
      allowed.add('http://localhost:3000');
      allowed.add('http://localhost:3005');
      allowed.add('http://127.0.0.1:3000');
      allowed.add('http://127.0.0.1:3005');
    }

    if (allowed.has(origin) || allowed.has(origin.replace(/\/$/, ''))) {
      return null;
    }
  }

  // Neither trusted Sec-Fetch-Site nor allowed Origin present -> Fail closed
  return NextResponse.json(
    { error: 'Forbidden: Untrusted mutation source (CSRF protection)' },
    { status: 403 }
  );
}

// ── Rate Limiting (Edge Memory) ──────────────────────────────────────────────
const rateLimitMap = new Map<string, { count: number, resetTime: number }>();
function applyRateLimit(key: string, LIMIT: number): NextResponse | null {
  // Allow 150 requests per minute per IP for API routes
  const WINDOW_MS = 60 * 1000;
  
  const now = Date.now();

  let record = rateLimitMap.get(key);
  if (!record || now > record.resetTime) {
    record = { count: 1, resetTime: now + WINDOW_MS };
    rateLimitMap.set(key, record);
  } else {
    record.count++;
  }

  // Optional cleanup to prevent memory leak in long-running edge isolate
  if (Math.random() < 0.01) {
    for (const [k, v] of rateLimitMap.entries()) {
      if (now > v.resetTime) rateLimitMap.delete(k);
    }
  }

  if (record.count > LIMIT) {
    return NextResponse.json({
      error: 'Too Many Requests',
      message: 'Rate limit exceeded. Please try again later.'
    }, { status: 429, headers: { 'Retry-After': String(Math.ceil((record.resetTime - now) / 1000)) } });
  }

  return null;
}

// ── JWT Secret (Edge-compatible — TextEncoder only) ─────────────────────────
function getEdgeSecret(): Uint8Array {
  // We can't import requireSecret easily in edge middleware without messing up bundle,
  // so we inline the fail closed logic.
  const secret = process.env.JWT_SECRET;
  if (!secret) {
    throw new Error('CRITICAL SECURITY ERROR: JWT_SECRET is not defined.');
  }
  return new TextEncoder().encode(secret);
}

// ── Extract session JWT from cookies ─────────────────────────────────────────
async function extractSessionAddress(req: NextRequest): Promise<string | null> {
  // Priority 1: SIWE ledger session
  // `hl_session` is the designated primary cookie (B-007) — /api/siwe/verify
  // issues it and only writes the legacy names alongside it for compatibility.
  // It was missing from this lookup, so the perimeter was reading the
  // compatibility cookie and ignoring the real one. Removing the legacy write
  // would have broken every authenticated route at once, with nothing here to
  // explain why. Primary first, legacy names after it.
  const ledgerCookie = req.cookies.get('hl_session')?.value
    ?? req.cookies.get('humanity_session')?.value
    ?? req.cookies.get('ledger_session')?.value
    ?? req.cookies.get('human_session')?.value;

  if (ledgerCookie) {
    try {
      const isEdDSA = !!process.env.JWT_EDDSA_PUBLIC_JWK;
      let payload;
      
      if (isEdDSA) {
        const { importJWK } = await import('jose');
        const pubJwk = JSON.parse(process.env.JWT_EDDSA_PUBLIC_JWK!);
        const publicKey = await importJWK(pubJwk, 'EdDSA');
        const result = await jwtVerify(ledgerCookie, publicKey, { algorithms: ['EdDSA'] });
        payload = result.payload;
      } else {
        const result = await jwtVerify(ledgerCookie, getEdgeSecret(), { algorithms: ['HS256'] });
        payload = result.payload;
      }
      
      const addr = (payload as any).address ?? (payload as any).sub;
      if (addr && typeof addr === 'string') return addr.toLowerCase();
    } catch {
      // Expired or invalid JWT — fall through
    }
  }

  // Priority 2: Email/standard access token
  const accessToken = req.cookies.get('human.access-token')?.value;
  if (accessToken) {
    try {
      const { payload } = await jwtVerify(accessToken, getEdgeSecret());
      const userId = (payload as any).userId;
      if (userId && typeof userId === 'string') return userId.toLowerCase();
    } catch {
      // Expired or invalid JWT
    }
  }

  return null;
}

export async function middleware(req: NextRequest): Promise<NextResponse> {
  const { pathname } = req.nextUrl;
  let earlySession: string | null | undefined;

  // 1. Edge Rate Limiting for ALL API Routes
  if (pathname.startsWith('/api/')) {
    // T-12: Use the LAST hop of X-Forwarded-For (the Railway proxy IP closest to us).
    // Using the first hop is easy to spoof by injecting fake IPs. Last hop = trusted.
    const forwardedFor = req.headers.get('x-forwarded-for') || '';
    const hops = forwardedFor.split(',').map(h => h.trim()).filter(Boolean);
    const clientIp = hops.length > 0 ? hops[hops.length - 1] : ((req as any).ip || '127.0.0.1');
    // Retired routes answer 410 before anything else runs (lib/security/retiredRoutes.ts).
    if (isRetiredApiRoute(pathname)) {
      return NextResponse.json({ error: 'Gone', message: 'This endpoint has been retired.' }, { status: 410 });
    }

    // Signed-in requests are limited per account, everyone else per IP.
    // Keying everyone on IP alone throttled whole offices, universities and
    // mobile carriers (many people behind one carrier-grade NAT address) at
    // 150 requests a minute between them, and a chat tab alone makes ~30.
    earlySession = await extractSessionAddress(req);
    const rateLimitRes = earlySession
      ? applyRateLimit('u:' + earlySession, 600)
      : applyRateLimit('ip:' + clientIp, 150);
    if (rateLimitRes) return rateLimitRes;

    // B-015: Strict CSRF check on API mutations (webhooks excluded: they are
    // server-to-server and verify their own signatures). Academy routes are
    // checked too: progress and submissions change account data, and the
    // upload form posts from the same origin.
    if (!pathname.startsWith('/api/webhooks/')) {
      const csrfRes = checkCsrf(req);
      if (csrfRes) return csrfRes;
    }
  }

  // 2. Allow all public paths through immediately.
  // A-016: ALWAYS strip client-injected identity headers — even on public paths.
  if (isPublicPath(pathname)) {
    const sanitizedHeaders = new Headers(req.headers);
    sanitizedHeaders.delete('x-verified-session-address');
    sanitizedHeaders.delete('x-session-ts');
    sanitizedHeaders.delete('x-wallet-address');
    sanitizedHeaders.delete('x-web3-address');
    return NextResponse.next({ request: { headers: sanitizedHeaders } });
  }


  // Strict enforcement: ONLY /chat and /portfolio are allowed for authenticated users.
  // /terminal is strictly redirected to /chat. /hub is allowed.
  if (pathname === '/terminal' || pathname.startsWith('/terminal/') ) {
    return NextResponse.redirect(new URL('/chat', req.url));
  }

  // [FASE 3: App Hub Lock]
  const LOCKED_ROUTES = ['/dashboard', '/markets', '/governance', '/network', '/qds'];
  if (LOCKED_ROUTES.some(r => pathname.startsWith(r))) {
    return NextResponse.redirect(new URL('/chat', req.url));
  }

  // [FASE 18: OFAC / Restricted Jurisdiction Geofencing]
  // Blocks IP addresses from the US and OFAC-sanctioned countries at the edge for PROTECTED app routes.
  const country = req.headers.get('x-vercel-ip-country') || req.headers.get('cf-ipcountry') || '';
  const RESTRICTED_COUNTRIES = ['US', 'CU', 'IR', 'KP', 'SY', 'RU', 'BY'];
  
  if (country && RESTRICTED_COUNTRIES.includes(country.toUpperCase())) {
    return new NextResponse(
      `<!DOCTYPE html><html><head><title>Service Restricted</title>
       <meta name="viewport" content="width=device-width, initial-scale=1">
       <style>
         body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; background: #fafafa; color: #111; display: flex; align-items: center; justify-content: center; height: 100vh; margin: 0; padding: 20px; text-align: center; }
         .card { max-w: 500px; padding: 40px; background: #fff; border: 1px solid #eaeaea; border-radius: 12px; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.05); }
         h2 { margin-top: 0; font-size: 24px; font-weight: 700; letter-spacing: -0.02em; }
         p { color: #666; line-height: 1.6; margin-bottom: 24px; }
         a { display: inline-block; padding: 10px 20px; background: #111; color: #fff; text-decoration: none; border-radius: 6px; font-weight: 500; font-size: 14px; }
       </style>
       </head><body>
       <div class="card">
         <h2>Unavailable in ${country}</h2>
         <p>Humanity Ledger application services are currently unavailable in your jurisdiction due to regulatory restrictions.</p>
         <a href="/">Return to Home</a>
       </div>
       </body></html>`,
      { status: 451, headers: { 'content-type': 'text/html' } }
    );
  }

  // 3. Check for a valid session JWT
  const sessionAddress = earlySession !== undefined ? earlySession : await extractSessionAddress(req);

  if (!sessionAddress) {
    // No session at all → redirect to sign-in (for pages) or 401 (for API)
    if (pathname.startsWith('/api/')) {
      return NextResponse.json(
        {
          error: 'Authentication required.',
          code: 'NO_SESSION',
          hint: 'Connect your wallet and claim your Sovereign Identity at /sign-in',
        },
        { status: 401 }
      );
    }
    const signInUrl = new URL('/connect', req.url);
    signInUrl.searchParams.set('redirect', pathname);
    // Use 303 See Other to force the browser to change POST/PUT to GET
    // This fixes the HTTP 405 Method Not Allowed error when NextAuth or Server Actions
    // hit an unauthenticated route and get redirected to a Page.
    return NextResponse.redirect(signInUrl, 303);
  }

  // 3. Session exists → pass the address to downstream handlers via header
  //    A-016: First STRIP all client-injected identity headers, then inject verified one.
  //    This prevents any client-supplied header from being trusted downstream.
  //    Headers injected:
  //      x-verified-session-address → cryptographically verified wallet address (from JWT)
  //      x-session-ts               → timestamp for replay-attack detection in routes
  //      x-request-id               → unique request correlation ID for audit trail
  const requestHeaders = new Headers(req.headers);
  // A-016: Strip ALL client-injected identity headers BEFORE injecting verified ones
  requestHeaders.delete('x-web3-address');
  requestHeaders.delete('x-wallet-address');
  requestHeaders.delete('x-verified-session-address');
  requestHeaders.delete('x-session-ts');
  // Now safely inject the verified session address
  requestHeaders.set('x-verified-session-address', sessionAddress);
  requestHeaders.set('x-session-ts', String(Date.now()));
  const requestId = typeof crypto !== 'undefined' && crypto.randomUUID
    ? crypto.randomUUID()
    : Array.from(crypto.getRandomValues(new Uint8Array(16))).map(b => b.toString(16).padStart(2, '0')).join('');
  requestHeaders.set('x-request-id', requestId);

  const nonceBytes = typeof crypto !== 'undefined' && crypto.randomUUID
    ? crypto.randomUUID()
    : Array.from(crypto.getRandomValues(new Uint8Array(16))).map(b => b.toString(16).padStart(2, '0')).join('');
  const nonce = Buffer.from(nonceBytes).toString('base64');
  requestHeaders.set('x-nonce', nonce);

  const response = NextResponse.next({
    request: {
      headers: requestHeaders,
    },
  });
  response.headers.set('x-request-id', requestId);
  response.headers.set('x-nonce', nonce);

  // [SECURITY] B-016 / B-017: Unified strict CSP with nonce per request (N-05)
  response.headers.set(
    'Content-Security-Policy',
    `default-src 'self'; script-src 'self' 'nonce-${nonce}' 'wasm-unsafe-eval' https://js.stripe.com; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com data:; img-src 'self' data: blob: https:; connect-src 'self' https: wss: blob:; media-src 'self' blob: mediastream:; frame-src 'self' https:; worker-src 'self' blob:; object-src 'none'; base-uri 'self'; form-action 'self';`
  );

  // [SECURITY] Cross-Origin Isolation for Barretenberg WASM Multithreading (SharedArrayBuffer)
  if (req.nextUrl.pathname.startsWith('/prove')) {
    response.headers.set('Cross-Origin-Opener-Policy', 'same-origin');
    response.headers.set('Cross-Origin-Embedder-Policy', 'require-corp');
  }

  // [SECURITY] Additional hardening headers
  response.headers.set('Strict-Transport-Security', 'max-age=63072000; includeSubDomains; preload');
  response.headers.set('X-Content-Type-Options', 'nosniff');
  response.headers.set('X-Frame-Options', 'DENY');
  response.headers.set('X-XSS-Protection', '1; mode=block');
  response.headers.set('Referrer-Policy', 'strict-origin-when-cross-origin');
  response.headers.set('Permissions-Policy', 'camera=(self), microphone=(self), geolocation=(self)');

  // Community apps are untrusted code. Their document gets its own, stricter
  // policy (opaque-origin sandbox, no network) and may only be framed by us.
  // See lib/community-apps/framePolicy.ts.
  if (isAppFramePath(pathname)) {
    response.headers.set('Content-Security-Policy', APP_FRAME_CSP);
    response.headers.set('X-Frame-Options', 'SAMEORIGIN');
    response.headers.set('Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), clipboard-read=()');
    response.headers.set('Referrer-Policy', 'no-referrer');
  }

  return response;
}

